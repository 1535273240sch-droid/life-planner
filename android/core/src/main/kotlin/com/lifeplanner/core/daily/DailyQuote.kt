/**
 * 每日推送 / 首页“每日一句”的本地内容池。
 *
 * 设计原则：
 * - 完全离线、按日期确定性轮换：同一天多次打开内容一致，不需要网络或 AI，
 *   推送不会因为没配 Key 而失效。
 * - 内容分四块：励志短语（quote + author）、生活提醒、学习提醒、工作提醒，
 *   各自独立轮换，因此组合数量远大于条目数。
 * - 文案要求具体、可执行，禁止空泛口号。
 */
data class DailyQuote(
    val quote: String,
    val author: String,
    val lifeTip: String,
    val studyTip: String,
    val workTip: String,
)

