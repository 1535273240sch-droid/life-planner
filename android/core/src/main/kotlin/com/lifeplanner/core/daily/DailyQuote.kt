    /** 按日期取当天内容：同一天恒定，跨天自动换一组。 */
    fun forDate(date: LocalDate): DailyQuote {
        val day = date.toEpochDays()
        return DailyQuote(
            quote = QUOTES[Math.floorMod(day, QUOTES.size)].first,
            author = QUOTES[Math.floorMod(day, QUOTES.size)].second,
            lifeTip = LIFE_TIPS[Math.floorMod(day, LIFE_TIPS.size)],
            studyTip = STUDY_TIPS[Math.floorMod(day, STUDY_TIPS.size)],
            workTip = WORK_TIPS[Math.floorMod(day, WORK_TIPS.size)],
        )
    }

    /** 按小时给问候语（用于首页头部与早间推送标题）。 */
    fun greeting(hour: Int): String = when (hour) {
        in 5..8 -> "早上好"
        in 9..11 -> "上午好"
        in 12..13 -> "中午好"
        in 14..17 -> "下午好"
        in 18..22 -> "晚上好"
        else -> "夜深了"
    }

    /** 日期标签：10 月 17 日 · 周五 */
    fun dateLabel(date: LocalDate): String {
        val week = when (date.dayOfWeek.ordinal) {
            0 -> "周一"
            1 -> "周二"
            2 -> "周三"
            3 -> "周四"
            4 -> "周五"
            5 -> "周六"
            else -> "周日"
        }
        return "${date.monthNumber} 月 ${date.dayOfMonth} 日 · $week"
    }

